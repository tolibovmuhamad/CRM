import { buildFullName, type Student, type StudentGroupRef } from '@/shared/api/schemas';
import { groupsFixture } from './groups';

/** Ссылка на группу собирается из фикстуры групп — чтобы имена и даты не разъезжались. */
function groupRef(id: string): StudentGroupRef {
  const group = groupsFixture.find((g) => g.id === id);
  if (!group) throw new Error(`Фикстура студентов ссылается на несуществующую группу ${id}`);
  return { id: group.id, name: group.name, startDate: group.startDate, endDate: group.endDate };
}

/** `fullName` считается так же, как его считает мок при создании студента. */
type StudentSeed = Omit<Student, 'fullName' | 'groups'> & { groupIds: string[] };

const seed = (data: StudentSeed): Student => {
  const { groupIds, ...rest } = data;
  return {
    ...rest,
    fullName: buildFullName(data.firstName, data.lastName),
    groups: groupIds.map(groupRef),
  };
};

